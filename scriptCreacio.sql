DROP TABLE MITJA_TRANSPORT;
PAUSE "TAULA MITJA_TRANSPORT ELIMINADA"

DROP TABLE CIUTAT;
PAUSE "TAULA CIUTAT ELIMINADA"


CREATE TABLE CIUTAT (
    id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nom VARCHAR2(50 CHAR) CONSTRAINT NN_CIUTAT_NOM NOT NULL,
    CONSTRAINT PK_CIUTAT PRIMARY KEY (id)
);

PAUSE "TAULA CIUTAT CREADA"


CREATE TABLE MITJA_TRANSPORT (
    id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nom VARCHAR2(50 CHAR) CONSTRAINT NN_MITJATRANSPORT_NOM NOT NULL,
    CONSTRAINT PK_MITJA_TRANSPORT PRIMARY KEY (id)
);

PAUSE "TAULA MITJA_TRANSPORT CREADA"


CREATE TABLE USUARI (
    id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    email VARCHAR2(50 CHAR) CONSTRAINT NN_USUARI_EMAIL NOT NULL,
    nom VARCHAR2(50 CHAR) CONSTRAINT NN_USUARI_NOM NOT NULL,
    password VARCHAR2(50 CHAR) CONSTRAINT NN_USUARI_PASSWORD NOT NULL,
    tipus CHAR(1) CONSTRAINT NN_USUARI_TIPUS NOT NULL,
    dataRegistre DATE CONSTRAINT NN_USUARI_DATAREGISTRE NOT NULL,
    CONSTRAINT PK_USUARI PRIMARY KEY (id),
    CONSTRAINT CK_USUARI_TIPUS CHECK (tipus IN ('A', 'E', 'B'))
);

PAUSE "TAULA USUARI CREADA"


CREATE TABLE ESTACIO (
    id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nom VARCHAR2(50 CHAR) CONSTRAINT NN_ESTACIO_NOM NOT NULL,
    latitud NUMBER(9,6) CONSTRAINT NN_ESTACIO_LATITUD NOT NULL,
    longitud NUMBER(9,6) CONSTRAINT NN_ESTACIO_LONGITUD NOT NULL,
    id_ciutat NUMBER(3) CONSTRAINT NN_ESTACIO_IDCIUTAT NOT NULL,
    CONSTRAINT PK_ESTACIO PRIMARY KEY (id),
    CONSTRAINT FK_ESTACIO_CIUTAT FOREIGN KEY (id_ciutat) REFERENCES CIUTAT(id)
);

PAUSE "TAULA ESTACIO CREADA"


CREATE TABLE TRAJECTE (
    id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nom VARCHAR2(50 CHAR) CONSTRAINT NN_TRAJECTE_NOM NOT NULL,
    dataCreacio DATE CONSTRAINT NN_TRAJECTE_DATACREACIO NOT NULL,
    validat NUMBER(1) CONSTRAINT NN_TRAJECTE_VALIDAT NOT NULL,
    mitjaTransport NUMBER(3) CONSTRAINT NN_TRAJECTE_MITJATRANSPORT NOT NULL,
    usuariCreador NUMBER(3) CONSTRAINT NN_TRAJECTE_USUARICREADOR NOT NULL,
    CONSTRAINT PK_TRAJECTE PRIMARY KEY (id),
    CONSTRAINT FK_TRAJECTE_MITJATRANSPORT FOREIGN KEY (mitjaTransport) REFERENCES MITJA_TRANSPORT(id),
    CONSTRAINT FK_TRAJECTE_USUARICREADOR FOREIGN KEY (usuariCreador) REFERENCES USUARI(id),
    CONSTRAINT CK_TRAJECTE_VALIDAT CHECK (validat IN (0,1))
);

PAUSE "TAULA TRAJECTE CREADA"


CREATE TABLE PARADA (
    id_traj NUMBER(3),
    ordre NUMBER(3),
    nom VARCHAR2(50 CHAR) CONSTRAINT NN_PARADA_NOM NOT NULL,
    horaPas VARCHAR2(5 CHAR) CONSTRAINT NN_PARADA_HORAPAS NOT NULL,
    idEstacio NUMBER(3) CONSTRAINT NN_PARADA_IDESTACIO NOT NULL,
    CONSTRAINT PK_PARADA PRIMARY KEY (id_traj, ordre),
    CONSTRAINT FK_PARADA_TRAJECTE FOREIGN KEY (id_traj) REFERENCES TRAJECTE(id),
    CONSTRAINT FK_PARADA_ESTACIO FOREIGN KEY (idEstacio) REFERENCES ESTACIO(id),
    CONSTRAINT CK_PARADA_HORAPAS CHECK (REGEXP_LIKE(horaPas, '^([01][0-9]|2[0-3]):[0-5][0-9]$'))
);

PAUSE "TAULA PARADA CREADA"


CREATE UNIQUE INDEX IDX_CIUTAT_NOM ON CIUTAT (UPPER(nom));
CREATE UNIQUE INDEX IDX_MITJATRANSPORT_NOM ON MITJA_TRANSPORT (UPPER(nom));
CREATE UNIQUE INDEX IDX_USUARI_EMAIL ON USUARI (UPPER(email));
CREATE UNIQUE INDEX IDX_ESTACIO_NOM ON ESTACIO (id_ciutat,upper(nom));
CREATE UNIQUE INDEX IDX_TRAJECTE_NOM ON TRAJECTE (UPPER(nom));

PAUSE "INDEXS UNICS CREATS"